import sys

# Увеличим лимит рекурсии для больших n, хотя здесь рекурсии нет
# sys.setrecursionlimit(2000) 

def solve():
    """
    Основная функция для решения задачи.
    Использует бинарный поиск по ответу (минимальное максимальное недовольство k)
    и жадный алгоритм для проверки возможности.
    """
    try:
        # Чтение n
        n_str = sys.stdin.readline()
        if not n_str:
            return
        n = int(n_str.strip())
        
        # Чтение a_i
        a = list(map(int, sys.stdin.readline().split()))
        
        # Чтение b_i
        b = list(map(int, sys.stdin.readline().split()))
        
    except EOFError:
        return
    except Exception:
        return

    # Проверка на общий спрос и предложение
    total_demand = sum(a)
    total_supply = sum(b)

    if total_demand == 0:
        print(0)
        return
        
    if total_demand > total_supply:
        # Если общий спрос превышает общее предложение, решение невозможно
        print(-1)
        return

    # Функция проверки: возможно ли распределение с максимальным недовольством k
    def check(k: int) -> bool:
        """
        Проверяет, можно ли распределить всех кандидатов 
        так, чтобы max|i-j| <= k.
        """
        
        # 'remaining' будет хранить количество нераспределенных кандидатов 
        # для каждого дня, в который они изначально хотели прийти (индексы от 0 до n-1).
        remaining = list(a)
        
        # 'current_queue' - общая очередь нераспределенных кандидатов, 
        # которые могут пройти собеседование в текущий день i.
        current_queue = 0
        
        # 'start_idx' - индекс в 'remaining', с которого начинаются 
        # кандидаты, которые могут быть назначены на текущий день.
        start_idx = 0
        
        # Итерируемся по дням (индекс i от 0 до n-1)
        for i in range(n):
            
            # 1. Обновляем 'current_queue'
            # Кандидаты, которые хотели в день i, добавляются в очередь.
            current_queue += remaining[i]
            
            # 2. Обрабатываем "срочных" кандидатов
            # Кандидаты, которые хотели в день i-k-1, теперь не могут быть перенесены.
            # Они должны были пройти собеседование не позднее дня i-1. 
            # Поскольку мы обрабатываем дни по порядку, 
            # они должны были быть удовлетворены до дня i.
            
            # Кандидаты, которые хотели в день 'start_idx', могут пройти собеседование 
            # самое позднее в день 'start_idx + k'.
            # Если текущий день i > start_idx + k, то эти кандидаты не были распределены 
            # вовремя, и k не подходит.
            
            # Сдвигаем 'start_idx':
            # Кандидаты из дня 'start_idx' могут пройти собеседование 
            # самое позднее в день 'start_idx + k'.
            # Если 'i > start_idx + k', то эти кандидаты пропустили свой последний шанс.
            while start_idx < i and i > start_idx + k:
                # Если в 'remaining[start_idx]' остались нераспределенные кандидаты,
                # и мы уже прошли их последний возможный день, 
                # то это невозможное распределение.
                if remaining[start_idx] > 0:
                    return False
                # Кандидаты из 'start_idx' были полностью распределены (remaining[start_idx] == 0)
                # или они уже неактуальны для 'current_queue'.
                # Общая очередь 'current_queue' уменьшается на remaining[start_idx], 
                # так как они вышли из окна [i-k, i+k] для текущего дня i.
                current_queue -= remaining[start_idx]
                start_idx += 1
            
            # 3. Распределяем кандидатов
            # 'capacity' - сколько собеседований можем провести сегодня
            capacity = b[i]
            
            # 'assigned' - сколько кандидатов реально пройдут собеседование сегодня
            assigned = min(capacity, current_queue)
            
            # Обновляем 'current_queue' (сколько осталось нераспределенных)
            current_queue -= assigned
            
            # 4. Обновляем 'remaining' (жадное распределение)
            # Назначаем 'assigned' кандидатов, начиная с самого "старого" дня (start_idx).
            temp_assigned = assigned
            j = start_idx
            while temp_assigned > 0 and j <= i:
                can_take = remaining[j]
                take = min(temp_assigned, can_take)
                remaining[j] -= take
                temp_assigned -= take
                j += 1
                
        # 5. Финальная проверка: после прохода по всем дням
        # Кандидаты, которые хотели в день 'j', могут пройти собеседование 
        # самое позднее в день 'j+k'.
        # Если 'j+k' < n (последний день), то эти кандидаты должны быть распределены.
        for j in range(n):
            if remaining[j] > 0:
                # Если остался нераспределенный кандидат из дня j,
                # его крайний день j+k должен быть >= n (т.е. за пределами графика),
                # иначе k не подходит.
                # Но по логике, если total_demand <= total_supply, и мы дошли до конца,
                # все, кто остался, должны иметь возможность быть распределены 
                # до дня j+k.
                
                # Более простая проверка: 
                # Если current_queue > 0, то не все были распределены
                # Но current_queue уже обновлен до 0, если все влезли.
                # Достаточно проверить, что current_queue == 0
                pass
                
        return current_queue == 0

    # Бинарный поиск
    # Минимальное возможное k = 0
    # Максимальное возможное k = n-1 (максимальный перенос)
    low = 0
    high = n - 1 # max недовольство |1-n| = n-1

    # Учитываем, что a_i и b_i могут быть большими (до 10^9), 
    # а n до 10^6. Но max k - это n-1.
    # Бинарный поиск будет по k от 0 до n-1.

    min_k = -1

    while low <= high:
        mid = (low + high) // 2
        if check(mid):
            min_k = mid
            high = mid - 1 # Пытаемся найти меньшее k
        else:
            low = mid + 1 # Нужно большее k

    print(min_k)

# Запуск решения
solve()