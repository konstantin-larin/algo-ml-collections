# дана бинарная строка s длины n состоящая из символов 0 и 1
# под ней строится кв. таблица a размера n x n след образом:
# требуется найти макс. площадь в таблице, состоящую только из символов 1
# всего есть t наборов - число выводится в первой строке
# потом идет t строк s и для каждой надо вывести число - максимальную площадь таблицы
# накидаем общую структуру 
t = int(input())
for _ in range(t):
    s = input()
    n = len(s)
    # a = [[0] * n for __ in range(n)]
    # mod = n + 1    
    # print(n)

    # for i in range(n):
    #     for j in range(n):
